/*
 * TOTAL DE PROCESSOS DE HC - TRÁFICO DE DROGAS DE 2022 A 2025
 * 
 */
SELECT COUNT(*)
FROM 
	(SELECT * FROM DB2SA.PROCESSO WHERE COD_CLASSE = 15 AND IND_SEGREDO_JUST = 'N') p 
	INNER JOIN 
		(SELECT SEQ_ASSUNTO, SEQ_ASSUNTO_PAI FROM DB2SA.ASSUNTO_CNJ WHERE SEQ_ASSUNTO = 3607 OR SEQ_ASSUNTO_PAI = 3607) a ON a.SEQ_ASSUNTO = p.SEQ_ASSUNTO     	
WHERE  
  p.DT_RECEB_PROTOCOLO BETWEEN 
      TIMESTAMP '2022-01-01 00:00:00' AND TIMESTAMP '2025-12-31 23:59:59';


/*
 * TOTAL DE DOCUMENTOS
