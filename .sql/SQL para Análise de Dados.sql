SELECT ps.NUM_RG_JULGADO , ps.NUM_PET_JULGADA, d.SEQ_DOCUMENTO, d.SEQ_CGRMA_SES_PUBL,  d.COD_TIPO_DOC, sj.DT_SESSAO_JGTO, rj.DESC_RSULT_JGTO
FROM db2sa.INTEIRO_TEOR it 
INNER join db2sa.PROCESSO_SESSAO ps ON ps.SEQ_ITEOR  = it.SEQ_ITEOR
INNER JOIN db2sa.SESSAO_JULGAMENTO sj ON sj.SEQ_SESSAO = ps.SEQ_SESSAO
INNER JOIN db2sa.PROCESSO p ON p.NUM_REGISTRO  = ps.NUM_RG_JULGADO
INNER JOIN db2sa.DOCUMENTO_STJ d ON d.NUM_RG_DOC_STJ = ps.NUM_RG_JULGADO AND coalesce(d.num_pet_doc_stj, ' ') = COALESCE(ps.NUM_PET_JULGADA, ' ') 
INNER JOIN db2sa.RESULTADO_JGTO rj ON rj.COD_RSULT_JGTO  = ps.COD_RESULTADO_PROC
WHERE ps.IND_ACORDAO = 'S'
AND d.COD_TIPO_DOC IN ( 5, 91)
AND ps.NUM_RG_JULGADO  IN ('202404239253', '201403242065', '202501268646', '202500205629', '202401947543', '202401468800', '201602307583')
AND d.IND_EXCLUIDO  = 'N';

