SELECT 
	d.NUM_RG_DOC_STJ, d.SEQ_DOCUMENTO, td.DESC_TIPO_DESPACHO, te.DESC_TEOR_DECISAO 
FROM 
	db2sa.DOCUMENTO_STJ d 
INNER JOIN db2sa.TIPO_DESPACHO td ON td.SEQ_TIPO_DESPACHO  = d.SEQ_TIPO_DSPCH_DOC
INNER JOIN db2sa.TEOR_DECISAO te ON te.COD_TEOR_DECISAO  = td.COD_TEOR_DECISAO
WHERE d.SEQ_DOCUMENTO  IN (289569770, 333877547, 333670421,333700335,329587958);

SELECT DISTINCT te.COD_TEOR_DECISAO, te.DESC_TEOR_DECISAO, re.DESC_RSULT_JGTO, re.RESULTADO_RESUMIDO 
FROM DB2SA.TEOR_DECISAO te
INNER JOIN DB2SA.RESULTADO_JGTO re ON re.COD_TEOR_DECISAO = te.COD_TEOR_DECISAO
ORDER BY te.COD_TEOR_DECISAO;

