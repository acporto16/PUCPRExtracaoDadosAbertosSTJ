SELECT 
    p.NUM_REGISTRO,
    tp.DESC_TIPO_PECA,
    p.COD_NIVEL_SIGILO,
    p.IND_SEGREDO_JUST,
    ip.NUM_FOLHA_PECA,
    ipl.SEQ_PECA,
    ipl.seq_indc_proc_link    
FROM DB2SA.PROCESSO p
	 INNER JOIN DB2SA.INDICE_PROCESSO ip ON IP.NUM_REGISTRO = P.NUM_REGISTRO
	 INNER JOIN DB2SA.TIPO_PECA tp ON tp.COD_TIPO_PECA = ip.COD_TIPO_PECA
	 INNER JOIN DB2SA.INDC_PROC_LINK ipl ON IP.SEQ_PECA = IPL.SEQ_PECA AND ip.NUM_REGISTRO = ipl.NUM_REGISTRO
WHERE p.DT_AUTUACAO >= TO_DATE('2025-01-01 00:00', 'YYYY-MM-DD HH24:MI')
  AND p.DT_AUTUACAO <  TO_DATE('2025-12-31 00:00', 'YYYY-MM-DD HH24:MI')
  AND p.COD_CLASSE = 15
    AND IND_SEGREDO_JUST = 'N'  
	AND COALESCE(COD_NIVEL_SIGILO, '0') = '0'
	AND ipl.SEQ_TIPO_PECA_INDC = 207
ORDER BY num_registro, num_folha_peca;

