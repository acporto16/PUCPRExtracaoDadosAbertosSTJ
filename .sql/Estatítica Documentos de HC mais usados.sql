SELECT    
    --p.NUM_REGISTRO,
	c.NOME_CLASSE,
    tpi.DESC_TIPO_PECA_INDC,
    COUNT(*) TOTAL
FROM
    (SELECT p.NUM_REGISTRO, p.COD_CLASSE, p.DT_RECEB_PROTOCOLO, TO_NUMBER(TO_CHAR(p.DT_RECEB_PROTOCOLO, 'YYYY')) ANO_PROCESSO
     FROM DB2SA.PROCESSO p INNER JOIN DB2SA.ASSUNTO_CNJ a ON a.SEQ_ASSUNTO = p.SEQ_ASSUNTO
     WHERE COD_CLASSE = 15 AND a.SEQ_ASSUNTO_PAI = 3607) p
    INNER JOIN (SELECT COD_CLASSE, NOME_CLASSE FROM DB2SA.CLASSE) c ON c.COD_CLASSE = p.COD_CLASSE
    INNER JOIN (SELECT DISTINCT SEQ_PECA, NUM_REGISTRO, SEQ_TIPO_PECA_INDC FROM DB2SA.INDC_PROC_LINK WHERE SEQ_PECA = 1) tpl ON tpl.NUM_REGISTRO = p.NUM_REGISTRO
    INNER JOIN (SELECT COD_CLASSE, SEQ_TIPO_PECA_INDC, DESC_TIPO_PECA_INDC FROM DB2SA.TIPO_PECA_INDC WHERE COD_CLASSE = 15 AND SEQ_TIPO_PECA_INDC NOT IN (1123,207)) tpi ON tpi.SEQ_TIPO_PECA_INDC = tpl.SEQ_TIPO_PECA_INDC
WHERE    
	0 = 0
	AND (p.DT_RECEB_PROTOCOLO >= TIMESTAMP '2022-01-01 00:00:00'  AND p.DT_RECEB_PROTOCOLO <  TIMESTAMP '2025-12-31 23:59:59') 
	AND c.COD_CLASSE = 15
	AND tpl.SEQ_PECA = 1
	--AND tpi.SEQ_TIPO_PECA_INDC	= 209
GROUP BY c.NOME_CLASSE, tpi.DESC_TIPO_PECA_INDC	
ORDER BY 3 DESC	
	;

