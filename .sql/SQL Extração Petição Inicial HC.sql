SELECT 
	p.*,
    p.num_registro || '.' || p.seq_peca || '.'
        || CASE WHEN p.seq_indc_proc_link IS NOT NULL
                THEN TO_CHAR(p.seq_indc_proc_link) ELSE '' END AS id_peca	    
	--count(*)
FROM 
	(SELECT p.NUM_REGISTRO, DT_RECEB_PROTOCOLO, p.COD_CLASSE, p.IND_SEGREDO_JUST, p.SEQ_ASSUNTO, tp.DESC_TIPO_PECA, tp.SEQ_TIPO_PECA_INDC, tp.SEQ_INDC_PROC_LINK, tp.SEQ_PECA
	 FROM DB2SA.PROCESSO p	        
	 INNER JOIN
		(SELECT 		
			DISTINCT ipl.NUM_REGISTRO, tp.COD_TIPO_PECA, tp.DESC_TIPO_PECA, ipl.SEQ_TIPO_PECA_INDC, ipl.SEQ_INDC_PROC_LINK, ipl.SEQ_PECA
		FROM 
			DB2SA.INDC_PROC_LINK ipl
			INNER JOIN DB2SA.TIPO_PECA_INDC tpi ON tpi.SEQ_TIPO_PECA_INDC = ipl.SEQ_TIPO_PECA_INDC
			INNER JOIN DB2SA.TIPO_PECA tp ON tp.COD_TIPO_PECA = tpi.COD_TIPO_PECA
		WHERE 		
		tp.COD_TIPO_PECA = 'KH'
		) tp ON tp.NUM_REGISTRO = p.NUM_REGISTRO	
	 WHERE 
	 	p.COD_CLASSE = 15 AND p.IND_SEGREDO_JUST = 'N' 
		AND p.DT_RECEB_PROTOCOLO BETWEEN TIMESTAMP '2020-01-01 00:00:00' AND TIMESTAMP '2025-12-31 23:59:59'	
	) p 
	INNER JOIN 
		(SELECT SEQ_ASSUNTO, SEQ_ASSUNTO_PAI FROM DB2SA.ASSUNTO_CNJ WHERE SEQ_ASSUNTO = 3607 OR SEQ_ASSUNTO_PAI = 3607) a ON a.SEQ_ASSUNTO = p.SEQ_ASSUNTO     
ORDER BY NUM_REGISTRO, SEQ_TIPO_PECA_INDC
;