SELECT
    p.NUM_REGISTRO
    || '.'
    || p.SEQ_PECA
    || '.'
    || COALESCE(TO_CHAR(p.SEQ_INDC_PROC_LINK), '') AS ID_PECA
FROM (
    SELECT
        pr.NUM_REGISTRO,
        tp.SEQ_TIPO_PECA_INDC,
        tp.SEQ_INDC_PROC_LINK,
        tp.SEQ_PECA
    FROM DB2SA.PROCESSO pr
    INNER JOIN (
        SELECT
            ipl.NUM_REGISTRO,
            tp.COD_TIPO_PECA,
            tp.DESC_TIPO_PECA,
            ipl.SEQ_TIPO_PECA_INDC,
            ipl.SEQ_INDC_PROC_LINK,
            MAX(ipl.SEQ_PECA) AS SEQ_PECA
        FROM DB2SA.INDC_PROC_LINK ipl
        INNER JOIN DB2SA.TIPO_PECA_INDC tpi
            ON tpi.SEQ_TIPO_PECA_INDC = ipl.SEQ_TIPO_PECA_INDC
        INNER JOIN DB2SA.TIPO_PECA tp
            ON tp.COD_TIPO_PECA = tpi.COD_TIPO_PECA
        WHERE tp.COD_TIPO_PECA = 'KH'
        GROUP BY
            ipl.NUM_REGISTRO,
            tp.COD_TIPO_PECA,
            tp.DESC_TIPO_PECA,
            ipl.SEQ_TIPO_PECA_INDC,
            ipl.SEQ_INDC_PROC_LINK
    ) tp
        ON tp.NUM_REGISTRO = pr.NUM_REGISTRO
    WHERE pr.NUM_REGISTRO = '202602632550'
) p;

/*
 * USANDO VIEW PARA EVITAR A DUPLICAÇÃO DE REGISTROS. MESMO COM A VIEW É POSSÍVEL RETORNAR MAIS DE UM REGISTRO,
 * PORTANTO, FOI NECESSÁRIO OBTER A PEÇA MAIS RECENTE, POIS ESTAVA SENDO RETORNADO DUAS PETIÇÕES INICIAIS, A DO STJ
 * E A DO TRIBUNAL DE ORIGEM, EM ANÁLISE, OBSERVAMOS QUE AS PEÇAS MAIS ANTIGAS SÃO AS DO TRIBUNAL DE ORIGEM, ISTO É 
 * JUSTIFICADO PORQUE DURANTE A IMPETRAÇÃO DO HC NO STJ, OS PRIMEIROS DOCUMENTOS SÃO OS DO PRÓPRIO STJ, SENDO AS 
 * DEMAIS PEÇAS PROCESSUAIS IMPETRADAS DEPOIS.
 * 
 * AINDA HÁ UM RISCO DE SE OBTER A PETIÇÃO INICIAL DE HC DO TRIBUNAL DE ORIGEM, MAS CASO ISSO OCORRA, NÃO HAVERÁ 
 * PREJUÍZOS NO TREINAMENTO DO MODELO POIS ESTAMOS NOS REFERENCIANDO AO MESMO TIPO DE DOCUMENTO E O CONTEÚDO TEXTUAL
 * POSSUI MUITA SEMELHANÇA.
 */

SELECT
    resultado.ID_PECA
FROM (
    SELECT
        ipl.NUM_REGISTRO
        || '.'
        || ipl.SEQ_PECA
        || '.'
        || COALESCE(
            TO_CHAR(ipl.SEQ_INDC_PROC_LINK),
            ''
        ) AS ID_PECA,
        ROW_NUMBER() OVER (
            ORDER BY
                ipl.SEQ_INDC_PROC_LINK ASC,
                ipl.SEQ_PECA ASC
        ) AS RN
    FROM DB2SA.INDC_PROC_LINK ipl
    INNER JOIN DB2SA.VW_PECAS_ELETRONICAS_VISUALIZADOR v
        ON v.NUM_REGISTRO = ipl.NUM_REGISTRO
       AND v.SEQ_PECA = ipl.SEQ_PECA
    WHERE ipl.NUM_REGISTRO = '202602632550'
      AND ipl.SEQ_TIPO_PECA_INDC = 207
) resultado
WHERE resultado.RN = 1;